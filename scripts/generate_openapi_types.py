"""Generate deterministic TypeScript contracts from Argus OpenAPI.

Run on the validation host (gpu-validation):

    python scripts/generate_openapi_types.py
    python scripts/generate_openapi_types.py --check

The generator intentionally emits ``unknown`` for unconstrained schemas.  It
never emits TypeScript ``any``; endpoints need an explicit backend DTO before a
more specific generated type can appear.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = REPO_ROOT / "web" / "src" / "types" / "generated-openapi.ts"
CORE_PREFIXES = (
    "/api/analysis-tasks",
    "/api/analysis-task-templates",
    "/api/analysis-task-models",
    "/api/alerts",
    "/api/cameras",
    "/api/config",
    "/api/models",
    "/api/physics",
    "/api/replay",
    "/api/system",
)
HTTP_METHODS = ("delete", "get", "patch", "post", "put")


def _schema_type(schema: object) -> str:
    if not isinstance(schema, dict) or not schema:
        return "unknown"

    ref = schema.get("$ref")
    if isinstance(ref, str):
        return ref.rsplit("/", 1)[-1]

    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)

    enum = schema.get("enum")
    if isinstance(enum, list) and enum:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in enum)

    for composition, separator in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        values = schema.get(composition)
        if isinstance(values, list) and values:
            return separator.join(f"({_schema_type(value)})" for value in values)

    schema_type = schema.get("type")
    if isinstance(schema_type, list):
        return " | ".join(_schema_type({**schema, "type": value}) for value in schema_type)
    if schema_type == "null":
        return "null"
    if schema_type == "string":
        return "string"
    if schema_type in {"integer", "number"}:
        return "number"
    if schema_type == "boolean":
        return "boolean"
    if schema_type == "array":
        return f"Array<{_schema_type(schema.get('items', {}))}>"

    properties = schema.get("properties")
    additional = schema.get("additionalProperties")
    if schema_type == "object" or isinstance(properties, dict) or additional is not None:
        required = set(schema.get("required", []))
        members: list[str] = []
        if isinstance(properties, dict):
            for name, value in sorted(properties.items()):
                key = name if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", name) else json.dumps(name)
                optional = "" if name in required else "?"
                members.append(f"  {key}{optional}: {_schema_type(value)}")
        if isinstance(additional, dict):
            members.append(f"  [key: string]: {_schema_type(additional)}")
        elif additional is True:
            members.append("  [key: string]: unknown")
        if not members:
            return "Record<string, unknown>"
        return "{\n" + "\n".join(members) + "\n}"

    return "unknown"


def _response_type(operation: dict[str, Any]) -> str:
    responses = operation.get("responses", {})
    for status in sorted(responses):
        if not (status.startswith("2") or status == "default"):
            continue
        response = responses[status]
        content = response.get("content", {}) if isinstance(response, dict) else {}
        json_schema = content.get("application/json", {}).get("schema")
        if json_schema is not None:
            return _schema_type(json_schema)
        if content:
            return "Blob"
    return "void"


def _request_type(operation: dict[str, Any]) -> str:
    body = operation.get("requestBody")
    if not isinstance(body, dict):
        return "void"
    content = body.get("content", {})
    for media_type in (
        "application/json",
        "application/x-www-form-urlencoded",
        "multipart/form-data",
    ):
        schema = content.get(media_type, {}).get("schema")
        if schema is not None:
            return _schema_type(schema)
    return "unknown"


def _build_openapi() -> dict[str, Any]:
    sys.path.insert(0, str(REPO_ROOT / "src"))
    from argus.config.schema import ArgusConfig, DashboardConfig
    from argus.dashboard.app import create_app

    app = create_app(config=ArgusConfig(
        dashboard=DashboardConfig(go2rtc_enabled=False),
    ))
    return app.openapi()


def render_types(schema: dict[str, Any]) -> str:
    lines = [
        "// Generated by scripts/generate_openapi_types.py; DO NOT EDIT.",
        "// Regenerate and verify this file on gpu-validation.",
        "",
    ]
    components = schema.get("components", {}).get("schemas", {})
    for name, component in sorted(components.items()):
        rendered = _schema_type(component)
        lines.append(f"export type {name} = {rendered}")
        lines.append("")

    operations: list[tuple[str, str, dict[str, Any]]] = []
    for path, item in sorted(schema.get("paths", {}).items()):
        if not path.startswith(CORE_PREFIXES) or not isinstance(item, dict):
            continue
        for method in HTTP_METHODS:
            operation = item.get(method)
            if isinstance(operation, dict):
                operations.append((method.upper(), path, operation))

    lines.append("export interface CoreApiOperations {")
    for method, path, operation in operations:
        key = json.dumps(f"{method} {path}")
        request_type = _request_type(operation)
        response_type = _response_type(operation)
        lines.extend([
            f"  {key}: {{",
            f"    request: {request_type}",
            f"    response: {response_type}",
            "  }",
        ])
    lines.extend([
        "}",
        "",
        "export type CoreApiOperation = keyof CoreApiOperations",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    rendered = render_types(_build_openapi())
    output = args.output.resolve()
    if args.check:
        existing = output.read_text(encoding="utf-8") if output.exists() else ""
        if existing != rendered:
            print(
                f"generated OpenAPI types are stale: {output}\n"
                "run: python scripts/generate_openapi_types.py",
                file=sys.stderr,
            )
            return 1
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(rendered, encoding="utf-8", newline="\n")
    print(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
